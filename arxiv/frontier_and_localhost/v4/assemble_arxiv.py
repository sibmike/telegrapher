"""Assemble the arXiv manuscript of *Frontier and Localhost* (v4, October 2026).

Source of truth is the IEEE Access package (../../../ieee_access/paper_frontier_and_localhost):
  body             submission/sections/{I_III ... XI_open_problems_conclusion}.md
  appendices A, B  submission/sections/app{A_formal,B_gates}.md
  appendices C-I   submission/supplementary.md (generated by that package's scripts/generate_supplementary.py;
                   its S2-S7 become C-H and the full score table S1 becomes I)
  abstract         submission/abstract.md

This script only re-targets that text for a one-column article: figure widths, "Supplementary
Material S<n>" pointers -> appendix cross-references, IEEE-specific wording, and the literal
section labels of the supplementary -> REF() tokens that postprocess_tex.py turns into \\ref.
Run by build.sh; writes paper_frontier_and_localhost.md beside this file.
"""
import io, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
IEEE = os.path.normpath(os.path.join(HERE, "..", "..", "..", "ieee_access", "paper_frontier_and_localhost"))
SEC = os.path.join(IEEE, "submission", "sections")
OUT = os.path.join(HERE, "paper_frontier_and_localhost.md")

def rd(p): return io.open(p, encoding="utf-8").read()

BODY = ["I_III.md", "IV_feedback_signal_classes.md", "V_method.md", "VI_findings.md", "VII_design_space.md",
        "VIII_families.md", "IX_missing_architecture.md", "X_failure_surface.md", "XI_open_problems_conclusion.md"]
APPS = ["appA_formal.md", "appB_gates.md"]
ROMAN = ["I", "II", "III", "IV", "V", "VI", "VII", "VIII", "IX", "X", "XI"]
SEC_IDS = dict(zip(ROMAN, ["intro", "why", "loop", "signal", "method", "findings", "design", "families", "gap", "failure", "open"]))
ARABIC = {r: str(i + 1) for i, r in enumerate(ROMAN)}
SUPP = {"1": "scores", "2": "data", "3": "mechanism", "4": "contrast", "5": "families", "6": "audit", "7": "related"}
SUPP_ORDER = ["2", "3", "4", "5", "6", "7", "1"]

warnings = []

def common(t):
    t = re.sub(r"Supplementary Material S([1-7])\b", lambda m: "Appendix REF(app:%s)" % SUPP[m.group(1)], t)
    t = re.sub(r"\bthe IEEE (?:version|text)\b", "this version", t)
    return t

def figures(t):
    t = t.replace("\\begin{figure}[!t]", "\\begin{figure}[htbp]")
    t = re.sub(r"width=0\.9\\columnwidth\]\{(\w+?)_ieee\}", r"width=0.5\\textwidth]{figures/\1}", t)
    t = re.sub(r"width=\\columnwidth\]\{(\w+?)_ieee\}", r"width=0.55\\textwidth]{figures/\1}", t)
    t = re.sub(r"width=\\textwidth\]\{(\w+?)_ieee\}", r"width=\\textwidth]{figures/\1}", t)
    return t

def sec_ref(m):
    r = m.group(1)
    if r not in SEC_IDS:
        warnings.append("unmapped section numeral left as is: " + m.group(0))
        return m.group(0)
    return "Section REF(sec:%s)" % SEC_IDS[r]

def headings(block, n):
    """'# S4. Title' -> '## Title {#app:contrast}'; '### S4.1.1 Title' -> '#### Title {#app:contrast-1-1}'.
    Section numerals inside a heading become arabic numerals directly (no \\ref inside \\section)."""
    name = SUPP[n]
    def h(m):
        hashes, num, title = m.group(1), m.group(2), m.group(3).strip()
        sub = num.split(".")[1:]
        ident = "app:" + name + ("-" + "-".join(sub) if sub else "")
        title = re.sub(r"Section ([IVX]+)\b", lambda k: "Section " + ARABIC.get(k.group(1), k.group(1)), title)
        return "#" * (len(hashes) + 1) + " " + title + " {#" + ident + "}"
    return re.sub(r"(?m)^(#+) S(\d(?:\.\d+)*)\.?\s+(.*)$", h, block)

def lifted(t):
    """Supplementary prose: literal labels -> cross-reference tokens."""
    t = re.sub(r"Sections S(\d)\.(\d+)–S\d\.(\d+)",
               lambda m: "Appendices REF(app:%s-%s)–REF(app:%s-%s)" % (SUPP[m.group(1)], m.group(2), SUPP[m.group(1)], m.group(3)), t)
    t = re.sub(r"Section S(\d)((?:\.\d+)*)", lambda m: "Appendix REF(app:%s%s)" % (SUPP[m.group(1)], m.group(2).replace(".", "-")), t)
    t = t.replace("Appendix XII-D of the main text", "Appendix REF(app:formal)")
    t = t.replace("Appendix XIII", "Appendix REF(app:gates)").replace("Appendix XII", "Appendix REF(app:formal)")
    t = re.sub(r"Sections ([IVX]+)–([IVX]+)",
               lambda m: "Sections REF(sec:%s)–REF(sec:%s)" % (SEC_IDS.get(m.group(1), m.group(1)), SEC_IDS.get(m.group(2), m.group(2))), t)
    t = re.sub(r"Section ([IVX]+)\b", sec_ref, t)
    t = re.sub(r"Table ([IVX]+)-(\d+)\b", r"Table REF(tab:\1-\2)", t)
    t = t.replace("accompany this document", "are released as ancillary files with this preprint")
    t = re.sub(r"(?m)^---$\n", "", t)          # horizontal rules carried over from the earlier manuscript
    return common(shrink_code_blocks(t))

def shrink_code_blocks(t):
    """Plain fenced code blocks (the recount output) at a smaller size so their long lines fit the measure.
    Tracks fences line by line so the closing fence of a ```{=latex} block is never taken for an opening."""
    out, state = [], None            # state: None | "raw" | "code"
    for ln in t.split("\n"):
        bare = ln.strip() == "```"
        if state is None and ln.startswith("```{=latex}"):
            state = "raw"
        elif state is None and bare:
            state = "code"
            out += ["```{=latex}", "\\begingroup\\footnotesize", "```", ""]
        elif state == "raw" and bare:
            state = None
        elif state == "code" and bare:
            state = None
            out += [ln, "", "```{=latex}", "\\endgroup", "```"]
            continue
        out.append(ln)
    return "\n".join(out)

# ---------------------------------------------------------------- pieces
abstract = rd(os.path.join(IEEE, "submission", "abstract.md")).strip()
body = "\n\n".join(common(figures(rd(os.path.join(SEC, f)).strip())) for f in BODY)
apps = "\n\n".join(common(rd(os.path.join(SEC, f)).strip().replace("## Appendix: ", "## ", 1)) for f in APPS)

supp = rd(os.path.join(IEEE, "submission", "supplementary.md"))
i = supp.find("\n# S1. ")
if i < 0:
    sys.exit("supplementary.md: no '# S1.' heading")
supp = supp[i + 1:]
blocks = {}
for part in re.split(r"(?m)^(?=# S[1-7]\. )", supp):
    m = re.match(r"# S([1-7])\. ", part)
    if m:
        blocks[m.group(1)] = part.strip()
missing = [n for n in SUPP_ORDER if n not in blocks]
if missing:
    sys.exit("supplementary.md: missing sections S" + ", S".join(missing))
supp_md = "\n\n".join(lifted(headings(blocks[n], n)) for n in SUPP_ORDER)

UNICODE = [
    ("2260", r"\ensuremath{\neq}"), ("2265", r"\ensuremath{\geq}"), ("2264", r"\ensuremath{\leq}"), ("2192", r"\ensuremath{\rightarrow}"),
    ("2282", r"\ensuremath{\subset}"), ("2248", r"\ensuremath{\approx}"), ("00D7", r"\ensuremath{\times}"), ("2211", r"\ensuremath{\sum}"),
    ("221E", r"\ensuremath{\infty}"), ("03B5", r"\ensuremath{\varepsilon}"), ("03C4", r"\ensuremath{\tau}"), ("03BB", r"\ensuremath{\lambda}"),
    ("03A9", r"\ensuremath{\Omega}"), ("03B8", r"\ensuremath{\theta}"), ("2208", r"\ensuremath{\in}"), ("2026", r"\ldots"),
    ("2020", r"\dag"), ("2021", r"\ddag"), ("00A7", r"\S"), ("03BA", r"\ensuremath{\kappa}"), ("03B1", r"\ensuremath{\alpha}"),
    ("03B2", r"\ensuremath{\beta}"), ("03B4", r"\ensuremath{\delta}"), ("03B3", r"\ensuremath{\gamma}"), ("2295", r"\ensuremath{\oplus}"),
    ("2218", r"\ensuremath{\circ}"), ("2212", r"-"), ("2070", r"\ensuremath{^0}"), ("00B1", r"\ensuremath{\pm}"), ("200B", r"\hskip0pt"),
]

AUTHORS = [
    ("Mikhail L. Arbuzov", "Independent Researcher", "mike.arbuzov54@gmail.com"),
    ("Lee Mosbacker", "Independent Researcher", "lee.mosbacker@gmail.com"),
    ("Sisong Bei", "Independent Researcher", "qurining@gmail.com"),
    ("Ziwei Dong", "Independent Researcher", "ziwei.dong@alumni.emory.edu"),
    ("Dmitri Kalaev", "Independent Researcher", "kalaevdr@gmail.com"),
    ("Alexey A. Shvets", "Palo Alto Networks", "ashvets@paloaltonetworks.com"),
]

yaml = ['---', 'title: "Frontier and Localhost: A Survey of How Production AI Learns Outside the Weights"', 'author:']
for name, affil, mail in AUTHORS:
    yaml += ["  - |", "    %s  " % name, "    %s  " % affil, "    %s" % mail]
yaml += ['date: ""', "abstract: |", "  " + abstract, "header-includes:", "  - \\usepackage{xurl}", "  - \\usepackage{calc}"]
yaml += ["  - \\DeclareUnicodeCharacter{%s}{%s}" % (c, r) for c, r in UNICODE]
yaml += ["---", ""]

ack = ("## Acknowledgments {-}\n\n"
       "The authors used an AI assistant (Claude, Anthropic) to help search the literature, check citations, and edit prose; "
       "all claims, scores, and classifications were reviewed and approved by the authors.\n")
refs = "```{=latex}\n\\bibliography{references}\n\\appendix\n```\n"      # \bibliographystyle comes from pandoc's biblio-style

doc = "\n".join(yaml) + body + "\n\n" + ack + "\n" + refs + "\n" + apps + "\n\n" + supp_md + "\n"
io.open(OUT, "w", encoding="utf-8", newline="\n").write(doc)
for w in warnings:
    print("WARNING:", w)
leftover = sorted(set(re.findall(r"(?:Section|Appendix|Supplementary)[^\n]{0,3}\b(?:S[1-7]|[IVX]{1,4})\b", doc)))
print("assembled", os.path.basename(OUT), "| words:", len(doc.split()), "| unresolved literal labels:", leftover or "none")
